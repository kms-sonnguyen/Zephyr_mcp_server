#!/usr/bin/env node
// Builds the self-contained `zephyr-scale` agent skill from the compiled server:
//   1. bundles build/cli.js (+ axios, MCP SDK types) into skills/zephyr-scale/scripts/zephyr.mjs
//   2. regenerates skills/zephyr-scale/references/tools.md from the tool schemas
// Run after `tsc` (wired into `npm run build`). The skill folder can then be copied
// to ~/.claude/skills/ (or any agent's skills dir) and needs only Node >= 18.
import { build } from 'esbuild';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const skillDir = join(root, 'skills', 'zephyr-scale');
mkdirSync(join(skillDir, 'scripts'), { recursive: true });
mkdirSync(join(skillDir, 'references'), { recursive: true });

await build({
  entryPoints: [join(root, 'build', 'cli.js')],
  outfile: join(skillDir, 'scripts', 'zephyr.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  minify: true,
  legalComments: 'none',
  // Bundled CJS deps (axios' form-data etc.) call require(); give ESM output one.
  banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  logLevel: 'warning',
});

const { toolSchemas } = await import(join(root, 'build', 'tool-schemas.js'));

function typeOf(p) {
  if (p.enum) return p.enum.map((v) => `\`${v}\``).join(' \\| ');
  if (p.type === 'array') return `${p.items?.type ?? 'any'}[]`;
  return p.type ?? 'any';
}

function cell(s) {
  return String(s ?? '').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
}

const lines = [
  '# Zephyr Scale tool reference',
  '',
  '<!-- Generated by scripts/build-skill.mjs from src/tool-schemas.ts. Do not edit by hand. -->',
  '',
  'Run any tool with `node scripts/zephyr.mjs <tool> \'<json>\'` (or JSON on stdin).',
  'Nested object shapes are abbreviated here; `node scripts/zephyr.mjs help <tool>` prints the full JSON schema.',
  '',
  '| Tool | Kind | Platform |',
  '|---|---|---|',
  ...toolSchemas.map((t) => {
    const a = t.annotations ?? {};
    const kind = a.destructiveHint ? '**destructive**' : a.readOnlyHint ? 'read' : 'write';
    const platform = /cloud[ -]only/i.test(t.description) ? 'Cloud only' : 'Cloud + DC';
    return `| [\`${t.name}\`](#${t.name}) | ${kind} | ${platform} |`;
  }),
  '',
];

for (const t of toolSchemas) {
  const props = t.inputSchema.properties ?? {};
  const required = new Set(t.inputSchema.required ?? []);
  lines.push(`## ${t.name}`, '', cell(t.description), '');
  const names = Object.keys(props);
  if (names.length === 0) {
    lines.push('_No arguments._', '');
    continue;
  }
  lines.push('| Arg | Type | Req | Description |', '|---|---|---|---|');
  for (const name of names) {
    const p = props[name];
    lines.push(`| \`${name}\` | ${cell(typeOf(p))} | ${required.has(name) ? 'yes' : ''} | ${cell(p.description)} |`);
  }
  lines.push('');
}

writeFileSync(join(skillDir, 'references', 'tools.md'), lines.join('\n'));
console.log(`zephyr-scale skill built: ${toolSchemas.length} tools`);
